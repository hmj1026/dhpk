#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { extract, extractMetadata } = require('./_lib/frontmatter');
const { validateNextGraph } = require('../lib/skill-next-map');

function collectDeclarations(root) {
  const skills = {};
  const visit = directory => {
    if (!fs.existsSync(directory)) return;
    const entry = path.join(directory, 'SKILL.md');
    if (fs.existsSync(entry)) {
      const content = fs.readFileSync(entry, 'utf8');
      const name = extract(content).values.name;
      if (name) skills[name] = extractMetadata(content);
      return;
    }
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      if (entry.isDirectory() && !entry.name.startsWith('.')) visit(path.join(directory, entry.name));
    }
  };
  visit(path.join(root, 'skills'));
  visit(path.join(root, 'modules'));
  return skills;
}

function renderProgressionTable(skills) {
  const errors = validateNextGraph(skills);
  if (errors.length) throw new Error(errors.join('\n'));
  const lines = [
    '# Progression Tables',
    '',
    '<!-- Generated by scripts/ci/gen-skill-progression-tables.js; edit canonical SKILL.md metadata. -->',
    '',
    'Agent fallback only. The next analyzer follows canonical frontmatter declarations.',
    '',
    '| Skill | Result | Next identity |',
    '| --- | --- | --- |',
  ];
  for (const name of Object.keys(skills).sort()) {
    const next = skills[name].values['dhpk-next'];
    if (!next) continue;
    for (const [state, target] of Object.entries(next)) lines.push(`| ${name} | ${state} | ${target} |`);
  }
  return `${lines.join('\n')}\n`;
}

function checkProgressionTable(skills, content) {
  return content === renderProgressionTable(skills) ? [] : ['progression-tables.md is stale; run node scripts/ci/gen-skill-progression-tables.js --write'];
}

if (require.main === module) {
  const root = path.resolve(__dirname, '..', '..');
  const output = path.join(root, 'skills', 'flow-guide', 'references', 'progression-tables.md');
  try {
    const skills = collectDeclarations(root);
    if (process.argv.includes('--write')) {
      fs.writeFileSync(output, renderProgressionTable(skills));
      console.log('Wrote skills/flow-guide/references/progression-tables.md');
    } else {
      const errors = checkProgressionTable(skills, fs.readFileSync(output, 'utf8'));
      if (errors.length) throw new Error(errors.join('\n'));
      console.log('Progression table is current.');
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { collectDeclarations, renderProgressionTable, checkProgressionTable };
