'use strict';

// Per-profile projection sets (ADR-0023, #618). For every install profile and
// every Host whose native installer delegates skills to the Shared Project
// Projection, the set is the profile's resolved skill IDs filtered to skills
// whose inventory entry lists that Host's surface. catalog.js generates the
// declared manifest from this module and --check fails when it is stale, so
// installers read a reviewed set instead of computing one at install time.

const { resolveCapabilitySelection } = require('./capability-bundle-selection');

const SCHEMA = 'dhpk.profile-projection-sets.v1';
const MANIFEST_REL = 'manifests/profile-projection-sets.json';

// Host (installer surface name) -> inventory surface its skills must list.
const HOST_SURFACES = Object.freeze({
  'codex-sync': 'codex-sync',
  cursor: 'cursor-sync',
});

// Resolved IDs already exclude deprecated and non-invokable entries, so this
// only needs the surface membership listed on each inventory entry.
function surfaceSkillIds(inventory, surface) {
  return new Set(inventory.skills
    .filter((entry) => Array.isArray(entry.surfaces) && entry.surfaces.includes(surface))
    .map((entry) => entry.id));
}

function computeProfileProjectionSets({ inventory, profiles, moduleCatalog }) {
  const profileTable = profiles && profiles.profiles;
  if (!profileTable || typeof profileTable !== 'object') {
    throw new Error('install profiles manifest has no "profiles" table');
  }
  if (!inventory || !Array.isArray(inventory.skills)) {
    throw new Error('distribution inventory has no "skills" array');
  }
  const hosts = Object.keys(HOST_SURFACES).sort();
  const surfaceIds = Object.fromEntries(hosts.map((host) => [host, surfaceSkillIds(inventory, HOST_SURFACES[host])]));
  const sets = {};
  for (const profileId of Object.keys(profileTable).sort()) {
    const resolved = resolveCapabilitySelection({
      inventory,
      profiles,
      moduleCatalog,
      profileId,
      policyVersion: inventory.profile_policy && inventory.profile_policy.version,
    });
    if (!resolved.ok) {
      throw new Error(`cannot resolve install profile '${profileId}': ${resolved.error.message}`);
    }
    const selected = resolved.value.selectedStableIds;
    sets[profileId] = Object.fromEntries(hosts.map((host) => [
      host,
      selected.filter((id) => surfaceIds[host].has(id)).sort(),
    ]));
  }
  return {
    schema: SCHEMA,
    description: `Generated by scripts/ci/catalog.js --write; do not edit by hand. Per install profile and Host, the skill IDs projected into the Shared Project Projection: the profile's resolved skill IDs filtered to skills whose inventory lists the Host's surface (ADR-0023).`,
    hostSurfaces: Object.fromEntries(hosts.map((host) => [host, HOST_SURFACES[host]])),
    profiles: sets,
  };
}

function formatProfileProjectionSets(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

// One entry per (profile, Host) whose declared set differs from the expected
// one, including a profile or Host that is missing or no longer exists.
function diffProfileProjectionSets(declared, expected) {
  const declaredProfiles = declared && declared.profiles && typeof declared.profiles === 'object'
    ? declared.profiles
    : {};
  const drift = [];
  const profileIds = [...new Set([...Object.keys(expected.profiles), ...Object.keys(declaredProfiles)])].sort();
  for (const profileId of profileIds) {
    const want = expected.profiles[profileId] || {};
    const have = declaredProfiles[profileId] || {};
    const hosts = [...new Set([...Object.keys(want), ...Object.keys(have)])].sort();
    for (const host of hosts) {
      const wantIds = Array.isArray(want[host]) ? want[host] : null;
      const haveIds = Array.isArray(have[host]) ? have[host] : null;
      if (wantIds && haveIds && JSON.stringify(wantIds) === JSON.stringify(haveIds)) continue;
      const wantSet = new Set(wantIds || []);
      const haveSet = new Set(haveIds || []);
      drift.push({
        profileId,
        host,
        reason: !haveIds ? 'undeclared' : !wantIds ? 'unknown' : 'stale',
        missing: [...wantSet].filter((id) => !haveSet.has(id)),
        unexpected: [...haveSet].filter((id) => !wantSet.has(id)),
      });
    }
  }
  return drift;
}

function describeDrift(entry) {
  const parts = [];
  if (entry.reason === 'undeclared') parts.push('no declared projection set');
  if (entry.reason === 'unknown') parts.push('declared for a profile or Host that is not generated');
  if (entry.missing.length > 0) parts.push(`missing: ${entry.missing.join(', ')}`);
  if (entry.unexpected.length > 0) parts.push(`unexpected: ${entry.unexpected.join(', ')}`);
  if (parts.length === 0) parts.push('order or formatting differs from the generated set');
  const surface = HOST_SURFACES[entry.host] ? ` (surface '${HOST_SURFACES[entry.host]}')` : '';
  return `profile '${entry.profileId}' Host '${entry.host}'${surface} projection set is stale (${parts.join('; ')})`;
}

module.exports = {
  SCHEMA,
  MANIFEST_REL,
  HOST_SURFACES,
  computeProfileProjectionSets,
  formatProfileProjectionSets,
  diffProfileProjectionSets,
  describeDrift,
};
